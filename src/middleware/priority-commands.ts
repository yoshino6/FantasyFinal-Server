const highestPriority = /^(?:菜单|状态|设备状态|服务器状态|注销账户|确认注销(?:账户)?|BOSS测试(?:离开)?)(?:$| )/;
const administratorPriority = /^(?:管理|测试二转|世界(?:生态管理|事件账本|内容预览|内容开关|内容权重)|玩家(?:数据核查|操作|核查)|全局设置|地图开关|全局倍率|地图切换|清空背包|全服玩家核查|管理日志(?:页|搜索|筛选)?|注销记录(?:页|搜索|筛选)?|恢复注销账号|确认覆盖恢复|BOSS(?:管理|刷新|消灭|上赏)|小怪(?:管理|刷新)|矿产(?:管理|刷新)|迷宫管理|重建迷宫|测试 (?:神装|解体)|管理员登录|给予权限|撤销权限|查看权限|管理员命令|管理员邮件)(?:$| )/;

export const isPriorityCommand = (key: string) => highestPriority.test(key) || administratorPriority.test(key);
