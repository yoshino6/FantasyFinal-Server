/** 每行都是该势力独立编写的「传闻 / 下一段应验 / 下一段反转」三段域民口吻。 */
const parse = (rows: string[]): FinanceScenario[] => rows.map((row, index) => {
  const parts = row.split('|');
  if (parts.length !== 3 || parts.some(part => !part.trim())) throw new Error(`势力新闻第 ${index + 1} 条缺少预言、应验或专属反转。`);
  return { prophecy: parts[0]!, fulfilled: parts[1]!, reversal: parts[2]! };
});

